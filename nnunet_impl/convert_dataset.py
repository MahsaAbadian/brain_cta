#!/usr/bin/env python3
"""Convert existing preprocessed TopBrain data into nnUNet v2 dataset layout.

This script reuses:
- training_data_resampled images/labels generated by this repo.
- Existing train/val split text files for fair comparison.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
from pathlib import Path
from typing import Iterable


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Build an nnUNet v2 raw dataset from this repo's resampled data and split files."
        )
    )
    parser.add_argument("--dataset-id", type=int, default=501, help="nnUNet dataset id.")
    parser.add_argument(
        "--dataset-name",
        type=str,
        default="TopBrainCTA",
        help="Dataset name suffix used in DatasetXXX_name folder.",
    )
    parser.add_argument(
        "--source-image-dir",
        type=Path,
        default=Path("training_data_resampled/imagesTr_topbrain_ct"),
        help="Existing preprocessed image directory.",
    )
    parser.add_argument(
        "--source-label-dir",
        type=Path,
        default=Path("training_data_resampled/labelsTr_topbrain_ct"),
        help="Existing preprocessed label directory.",
    )
    parser.add_argument(
        "--split-dir",
        type=Path,
        default=Path("training_data_resampled/split"),
        help="Directory containing train_cases.txt and val_cases.txt.",
    )
    parser.add_argument(
        "--labelmap-path",
        type=Path,
        default=Path("training_data_resampled/itksnap_labelmap_txt/labelmap_topbrain_ct.txt"),
        help="Labelmap file used to derive dataset labels metadata.",
    )
    parser.add_argument(
        "--nnunet-raw-dir",
        type=Path,
        default=Path("nnUNet_raw"),
        help="Root path for nnUNet raw datasets (nnUNet_raw env equivalent).",
    )
    parser.add_argument(
        "--nnunet-preprocessed-dir",
        type=Path,
        default=Path("nnUNet_preprocessed"),
        help="Root path for nnUNet preprocessed datasets (nnUNet_preprocessed env equivalent).",
    )
    parser.add_argument(
        "--link-mode",
        type=str,
        choices=("symlink", "hardlink", "copy"),
        default="symlink",
        help="How to materialize files in nnUNet dataset folders.",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Overwrite existing files in target directories when present.",
    )
    return parser.parse_args()


def _dataset_folder_name(dataset_id: int, dataset_name: str) -> str:
    clean_name = "".join(ch if ch.isalnum() else "_" for ch in dataset_name).strip("_")
    return f"Dataset{dataset_id:03d}_{clean_name}"


def _load_split_ids(split_dir: Path) -> tuple[list[str], list[str]]:
    train_path = split_dir / "train_cases.txt"
    val_path = split_dir / "val_cases.txt"
    if not train_path.is_file() or not val_path.is_file():
        raise FileNotFoundError(
            f"Missing split files in {split_dir}. Expected train_cases.txt and val_cases.txt."
        )
    train_ids = [x.strip() for x in train_path.read_text().splitlines() if x.strip()]
    val_ids = [x.strip() for x in val_path.read_text().splitlines() if x.strip()]
    train_ids = sorted(set(train_ids))
    val_ids = sorted(set(val_ids) - set(train_ids))
    return train_ids, val_ids


def _parse_labelmap(labelmap_path: Path) -> dict[str, int]:
    if not labelmap_path.is_file():
        raise FileNotFoundError(f"Labelmap file not found: {labelmap_path}")

    labels_by_id: dict[int, str] = {}
    for raw_line in labelmap_path.read_text().splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        tokens = line.split()
        try:
            class_id = int(tokens[0])
        except (ValueError, IndexError):
            continue
        quoted = re.findall(r'"([^"]+)"', raw_line)
        if quoted:
            class_name = quoted[-1]
        else:
            class_name = f"class_{class_id:02d}"
        class_name = class_name.strip('"').strip("'")
        class_name = class_name.replace(" ", "_")
        labels_by_id[class_id] = class_name

    if 0 not in labels_by_id:
        labels_by_id[0] = "background"
    if labels_by_id[0].lower() != "background":
        labels_by_id[0] = "background"

    labels: dict[str, int] = {}
    for class_id in sorted(labels_by_id):
        name = labels_by_id[class_id]
        if name in labels:
            name = f"{name}_{class_id:02d}"
        labels[name] = class_id
    return labels


def _prepare_path(dst: Path, *, force: bool) -> None:
    if dst.exists() or dst.is_symlink():
        if not force:
            return
        if dst.is_dir() and not dst.is_symlink():
            shutil.rmtree(dst)
        else:
            dst.unlink()


def _materialize(src: Path, dst: Path, mode: str, *, force: bool) -> None:
    if not src.is_file():
        raise FileNotFoundError(f"Missing source file: {src}")
    _prepare_path(dst, force=force)
    if dst.exists() or dst.is_symlink():
        return
    if mode == "symlink":
        dst.symlink_to(src.resolve())
    elif mode == "hardlink":
        dst.hardlink_to(src)
    else:
        shutil.copy2(src, dst)


def _copy_cases(
    train_case_ids: Iterable[str],
    val_case_ids: Iterable[str],
    source_image_dir: Path,
    source_label_dir: Path,
    images_tr_dir: Path,
    labels_tr_dir: Path,
    images_val_dir: Path,
    link_mode: str,
    *,
    force: bool,
) -> None:
    train_set = sorted(set(train_case_ids))
    val_set = sorted(set(val_case_ids))
    all_case_ids = sorted(set(train_set).union(val_set))

    for case_id in all_case_ids:
        image_src = source_image_dir / f"{case_id}_0000.nii.gz"
        label_src = source_label_dir / f"{case_id}.nii.gz"
        image_dst = images_tr_dir / f"{case_id}_0000.nii.gz"
        label_dst = labels_tr_dir / f"{case_id}.nii.gz"
        _materialize(image_src, image_dst, link_mode, force=force)
        _materialize(label_src, label_dst, link_mode, force=force)

    # Keep a dedicated validation inference input folder for nnUNet predict.
    for case_id in val_set:
        image_src = source_image_dir / f"{case_id}_0000.nii.gz"
        image_dst = images_val_dir / f"{case_id}_0000.nii.gz"
        _materialize(image_src, image_dst, link_mode, force=force)


def _write_dataset_json(
    dataset_json_path: Path,
    labels: dict[str, int],
    num_training: int,
    *,
    force: bool,
) -> None:
    if dataset_json_path.exists() and not force:
        return
    payload = {
        "channel_names": {"0": "CT"},
        "labels": labels,
        "numTraining": num_training,
        "file_ending": ".nii.gz",
    }
    dataset_json_path.write_text(json.dumps(payload, indent=2) + "\n")


def _write_split_json(
    split_json_path: Path,
    train_ids: list[str],
    val_ids: list[str],
    *,
    force: bool,
) -> None:
    if split_json_path.exists() and not force:
        return
    payload = [{"train": sorted(train_ids), "val": sorted(val_ids)}]
    split_json_path.parent.mkdir(parents=True, exist_ok=True)
    split_json_path.write_text(json.dumps(payload, indent=2) + "\n")


def main() -> int:
    args = parse_args()
    train_ids, val_ids = _load_split_ids(args.split_dir)
    all_ids = sorted(set(train_ids).union(val_ids))
    if not all_ids:
        raise RuntimeError("No case ids found from split files.")

    dataset_folder = _dataset_folder_name(args.dataset_id, args.dataset_name)
    raw_dataset_dir = args.nnunet_raw_dir / dataset_folder
    images_tr_dir = raw_dataset_dir / "imagesTr"
    labels_tr_dir = raw_dataset_dir / "labelsTr"
    images_val_dir = raw_dataset_dir / "imagesVal"

    images_tr_dir.mkdir(parents=True, exist_ok=True)
    labels_tr_dir.mkdir(parents=True, exist_ok=True)
    images_val_dir.mkdir(parents=True, exist_ok=True)

    _copy_cases(
        train_case_ids=train_ids,
        val_case_ids=val_ids,
        source_image_dir=args.source_image_dir,
        source_label_dir=args.source_label_dir,
        images_tr_dir=images_tr_dir,
        labels_tr_dir=labels_tr_dir,
        images_val_dir=images_val_dir,
        link_mode=args.link_mode,
        force=args.force,
    )

    labels = _parse_labelmap(args.labelmap_path)
    _write_dataset_json(
        raw_dataset_dir / "dataset.json",
        labels=labels,
        num_training=len(all_ids),
        force=args.force,
    )
    _write_split_json(
        raw_dataset_dir / "splits_final.json",
        train_ids=train_ids,
        val_ids=val_ids,
        force=args.force,
    )
    _write_split_json(
        args.nnunet_preprocessed_dir / dataset_folder / "splits_final.json",
        train_ids=train_ids,
        val_ids=val_ids,
        force=args.force,
    )

    print(f"Prepared nnUNet dataset: {raw_dataset_dir}")
    print(f"Train cases: {len(train_ids)} | Val cases: {len(val_ids)}")
    print(f"imagesVal (for inference): {images_val_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
